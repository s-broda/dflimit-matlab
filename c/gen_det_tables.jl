# Writes c/dfl_det_tables.c: the constant tables of the general engine, from the Julia engine DFLimit.DFDet (the reference):
#   DET_PATH_TABLES   the outer paths of cases DK, DU, DT (trend(-1), trend(0), trend(1)) at c = 0 with a zero start, as the
#                     package ships them in data/paths (read_path_table): t, t', the roots, log P, the weights
#   DET_FILON_TABLES  the data of Filon's rule on a panel of nq = 16, 24, 32, 48 Gauss-Legendre nodes (filondata: the
#                     barycentric weights and the derivatives of the interpolating polynomial at the ends, from the inverse
#                     of the Vandermonde matrix in 512-bit arithmetic), with the nodes of Julia's rule
# Run from the repository root with an environment in which DFLimit is the package (DFLimit.jl, branch engine-merge or later):
#   JLCAP_GB=4 jlcap --project=/path/to/env c/gen_det_tables.jl
using Printf
using DFLimit; const DG = DFLimit.DFDet
out = open(joinpath(@__DIR__, "dfl_det_tables.c"), "w")
println(out, "/* generated by c/gen_det_tables.jl from the Julia engine (DFLimit.DFDet and its data/paths): do not edit */")
println(out, "#include \"dfl_det_int.h\"")
function writevec(name, v)
    @printf(out, "static const double %s[%d] = {", name, length(v))
    for (k, x) in enumerate(v); @printf(out, "%s%.17g", k == 1 ? "" : ",", x); k % 6 == 0 && print(out, "\n"); end
    println(out, "};")
end
# (an infinite scalar as +-1e308, which the engine reads back as infinite: MSVC's INFINITY is not a constant expression in
# a static initializer)
cnum(x) = isnan(x) ? "0" : isinf(x) ? (x > 0 ? "1e308" : "-1e308") : @sprintf("%.17g", x)
cplx(v) = reduce(vcat, [[real(z), imag(z)] for z in vec(v)])
names = ("DK", "DU", "DT")
scs = Dict{String,Vector{Float64}}(); krs = Dict{String,NTuple{3,Int}}()
for (i, p) in enumerate(-1:1)
    Mo = DG.model(DG.prep(DG.trend(p)), :zero)
    CP = DG.read_path_table(DG.table_file(p), Mo)
    nm = names[i]
    writevec("T_$(nm)_t", cplx(CP.t)); writevec("T_$(nm)_dt", cplx(CP.dt)); writevec("T_$(nm)_R", cplx(CP.R))
    writevec("T_$(nm)_lP", cplx(CP.lP)); writevec("T_$(nm)_wt", CP.wt)
    scs[nm] = [CP.c, CP.tau, CP.tstar, CP.a, CP.b, CP.h, CP.phi, CP.minpos, CP.maxneg]
    krs[nm] = (length(CP.t), size(CP.R, 1), CP.Mo.rp)
end
println(out, "const det_path_table DET_PATH_TABLES[3] = {")
for nm in names
    sc = scs[nm]; K, r, rp = krs[nm]
    @printf(out, "  {%d, %d, %d, {%s}, T_%s_t, T_%s_dt, T_%s_R, T_%s_lP, T_%s_wt},\n", K, r, rp, join([cnum(x) for x in sc], ","), nm, nm, nm, nm, nm)
end
println(out, "};")
for nq in (16, 24, 32, 48)
    F = DG.filondata(nq)
    writevec("F$(nq)_z", F.z); writevec("F$(nq)_lam", F.lam); writevec("F$(nq)_D0", vec(F.D0)); writevec("F$(nq)_D1", vec(F.D1))
end
println(out, "const det_filon_table DET_FILON_TABLES[4] = {")
for nq in (16, 24, 32, 48); @printf(out, "  {%d, F%d_z, F%d_lam, F%d_D0, F%d_D1},\n", nq, nq, nq, nq, nq); end
println(out, "};")
close(out)
println("dfl_det_tables.c written: ", filesize(joinpath(@__DIR__, "dfl_det_tables.c")), " bytes")
